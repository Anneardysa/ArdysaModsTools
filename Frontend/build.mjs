const pagesDir = join(root, "src", "pages");
const outDir = resolve(root, "..", "Assets", "Html");
const stageDir = join(root, ".vite-out");
const viteBin = join(root, "node_modules", "vite", "bin", "vite.js");

const EXTERNAL_REFS_ALLOWED = new Set(["dota2_performance"]);

