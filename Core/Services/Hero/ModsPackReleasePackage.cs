using System;
using System.Collections.Generic;
using System.IO;
using System.IO.Compression;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Threading;
using System.Threading.Tasks;
using ArdysaModsTools.Core.Helpers;

namespace ArdysaModsTools.Core.Services.Hero
{
    public static class ModsPackReleasePackage
    {
        internal const string ItemsGamePath = "scripts/items/items_game.txt";
        internal const string LocalizationDir = "resource/localization";

        public const string ReleaseVpkName = "pak01_dir.vpk";
        public const string ReleaseZipName = "ModsPack.zip";
        public const string ReleaseHashName = "ModsPack.hash";
        public const string ReleaseIndexName = "modspack_index.txt";

        private const string IndexHeader =
            "// ModsPack items_game block index - generated by ArdysaModsTools (Skin Selector > Generate ModsPack)";

        public static string? PrepareTree(string extractDir, IReadOnlyCollection<(string heroId, string setName)> requested)
        {
            if (!Directory.Exists(extractDir))
                return "Build folder is missing.";

            string marker = Full(extractDir, ModInstallerService.OriginMarkerPath);
            if (!File.Exists(marker))
            {
                Directory.CreateDirectory(Path.GetDirectoryName(marker)!);
                File.WriteAllBytes(marker, new byte[] { 0 });
            }

            if (!File.Exists(Full(extractDir, ItemsGamePath)))
                return "The package has no items_game.txt.";

            string loc = Full(extractDir, LocalizationDir);
            if (!Directory.Exists(loc) || !Directory.EnumerateFiles(loc, "*", SearchOption.AllDirectories).Any())
                return "The package has no localization files.";

            string manifestPath = Full(extractDir, SkinManifestStore.TreeRelativePath);
            var manifest = File.Exists(manifestPath) ? SkinManifestStore.Parse(File.ReadAllText(manifestPath)) : null;
            if (manifest == null)
                return "The Skin Selector manifest (version/_ardysamods) is missing or does not verify.";

            return CompareSets(requested, manifest.Entries.Select(e => (e.HeroId, e.SetName)), "the manifest");
        }

        public static string? CompareSets(
            IEnumerable<(string heroId, string setName)> requested,
            IEnumerable<(string heroId, string setName)> actual,
            string where)
        {
            static string Key((string heroId, string setName) p) => $"{p.heroId}: {p.setName}";
            var want = new HashSet<string>(requested.Select(Key), StringComparer.OrdinalIgnoreCase);
            var have = new HashSet<string>(actual.Select(Key), StringComparer.OrdinalIgnoreCase);

            var missing = want.Where(k => !have.Contains(k)).ToList();
            var extra = have.Where(k => !want.Contains(k)).ToList();
            if (missing.Count == 0 && extra.Count == 0)
                return null;

            var why = new List<string>();
            if (missing.Count > 0) why.Add($"missing from {where}: {Names(missing)}");
            if (extra.Count > 0) why.Add($"in {where} but not selected: {Names(extra)}");
            return string.Join("; ", why) + ".";
        }

        public static string? BuildIndex(
            IReadOnlyDictionary<string, (string block, string heroId)> blocks, out string? error)
        {
            error = null;
            if (blocks == null || blocks.Count == 0)
            {
                error = "The package customizes no items — modspack_index.txt would be empty.";
                return null;
            }

            var sb = new StringBuilder(IndexHeader).Append('\n');
            foreach (var (_, (block, _)) in blocks.OrderBy(kv => long.TryParse(kv.Key, out var n) ? n : long.MaxValue)
                                                   .ThenBy(kv => kv.Key, StringComparer.Ordinal))
                sb.Append(KeyValuesBlockHelper.NormalizeKvText(block).TrimEnd()).Append('\n');
            string text = sb.ToString();

            var parsed = KeyValuesBlockHelper.ParseKvBlocks(text);
            var lost = blocks.Where(kv => !parsed.TryGetValue(kv.Key, out var back)
                    || back.TrimEnd() != KeyValuesBlockHelper.NormalizeKvText(kv.Value.block).TrimEnd())
                .Select(kv => kv.Key).ToList();
            if (lost.Count > 0 || parsed.Count != blocks.Count)
            {
                error = $"modspack_index.txt does not parse back to the patched blocks (item ids: {Names(lost)}).";
                return null;
            }
            return text;
        }

        public static string? StripPackageText(string extractDir)
        {
            string itemsGame = Full(extractDir, ItemsGamePath);
            string loc = Full(extractDir, LocalizationDir);
            try
            {
                if (File.Exists(itemsGame))
                {
                    File.SetAttributes(itemsGame, FileAttributes.Normal);
                    File.Delete(itemsGame);
                }
                if (Directory.Exists(loc))
                    Directory.Delete(loc, recursive: true);
            }
            catch (Exception ex)
            {
                return $"Could not remove the package text for the slim package: {ex.Message}";
            }

            return File.Exists(itemsGame) || Directory.Exists(loc)
                ? "The package text survived the strip — the slim package would carry stale item data."
                : null;
        }

        public static async Task<string?> SealAsync(
            string vpkPath,
            bool slim,
            Func<string, CancellationToken, Task<(VpkOrigin Origin, bool NeedsRebuild)>> classify,
            CancellationToken ct = default)
        {
            if (!VpkSignatureSection.Apply(vpkPath, out var error))
                return $"Could not add the signature section: {error}";
            if (!VpkSignatureSection.IsApplied(vpkPath))
                return "The signature section is not in the package after applying it.";

            var (origin, needsRebuild) = await classify(vpkPath, ct).ConfigureAwait(false);
            if (origin != VpkOrigin.Official)
                return $"The package classifies as {origin}, not Official (origin marker missing or unreadable).";
            if (slim && !needsRebuild)
                return "The slim package still carries its item data next to the manifest — installers would install it as-is instead of rebuilding it.";
            if (!slim && needsRebuild)
                return "The package lacks the Skin Selector manifest or its item data — the Skin Selector would not detect what it installs.";

            return null;
        }

        public static async Task<string?> ExportAsync(
            string releaseDir, string slimVpkPath, string indexText, CancellationToken ct = default)
        {
            releaseDir = Path.TrimEndingDirectorySeparator(Path.GetFullPath(releaseDir));
            string partial = releaseDir + ".partial";
            if (Directory.Exists(releaseDir) || File.Exists(releaseDir) || Directory.Exists(partial))
                return $"The release folder already exists: {releaseDir}";
            if (!File.Exists(slimVpkPath))
                return "The slim package is missing.";
            if (string.IsNullOrWhiteSpace(indexText))
                return "modspack_index.txt is empty.";

            try
            {
                Directory.CreateDirectory(partial);
                string vpk = Path.Combine(partial, ReleaseVpkName);
                string zip = Path.Combine(partial, ReleaseZipName);
                File.Copy(slimVpkPath, vpk);
                File.SetAttributes(vpk, FileAttributes.Normal);

                using (var archive = ZipFile.Open(zip, ZipArchiveMode.Create))
                    archive.CreateEntryFromFile(vpk, ReleaseVpkName, CompressionLevel.Optimal);

                string hash = await HashAsync(zip, ct).ConfigureAwait(false);
                await File.WriteAllTextAsync(Path.Combine(partial, ReleaseHashName), hash, new UTF8Encoding(false), ct).ConfigureAwait(false);
                await File.WriteAllTextAsync(Path.Combine(partial, ReleaseIndexName), indexText, new UTF8Encoding(false), ct).ConfigureAwait(false);

                using (var archive = ZipFile.OpenRead(zip))
                {
                    if (archive.Entries.Count != 1 || archive.Entries[0].FullName != ReleaseVpkName
                        || archive.Entries[0].Length != new FileInfo(vpk).Length)
                        return Abandon(partial, "ModsPack.zip does not hold exactly the release package.");
                }
                if (await HashAsync(zip, ct).ConfigureAwait(false) != hash)
                    return Abandon(partial, "ModsPack.hash does not match ModsPack.zip.");

                Directory.Move(partial, releaseDir);
                return null;
            }
            catch (OperationCanceledException)
            {
                Abandon(partial, string.Empty);
                throw;
            }
            catch (Exception ex)
            {
                return Abandon(partial, $"Could not write the release folder: {ex.Message}");
            }
        }

        private static async Task<string> HashAsync(string path, CancellationToken ct)
        {
            await using var stream = File.OpenRead(path);
            return Convert.ToHexString(await SHA256.HashDataAsync(stream, ct).ConfigureAwait(false)).ToLowerInvariant();
        }

        private static string Abandon(string partial, string error)
        {
            try { if (Directory.Exists(partial)) Directory.Delete(partial, true); } catch {  }
            return error;
        }

        private static string Names(IReadOnlyCollection<string> names)
            => names.Count <= 5 ? string.Join(", ", names) : string.Join(", ", names.Take(5)) + $" (+{names.Count - 5} more)";

        private static string Full(string root, string relative)
            => Path.Combine(root, relative.Replace('/', Path.DirectorySeparatorChar).Replace('\\', Path.DirectorySeparatorChar));
    }
}
